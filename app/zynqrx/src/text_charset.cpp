bool invisible(uint32_t c) {
    return c < 0x20 || (c >= 0x7F && c <= 0x9F) || c == 0xAD || (c >= 0x200B && c <= 0x200F) || (c >= 0x2028 && c <= 0x202E) ||
           (c >= 0x2060 && c <= 0x206F) || c == 0xFEFF || c == 0xFFFD || c == 0xFFFE || c == 0xFFFF || (c >= 0xD800 && c <= 0xDFFF) ||
           (c >= 0xFFF9 && c <= 0xFFFB) || c > 0x10FFFF;
}
