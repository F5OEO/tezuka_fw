void appendUtf8(std::string& o, uint32_t c) {
    if (c < 0x80) o += (char)c;
    else if (c < 0x800) { o += (char)(0xC0 | (c >> 6)); o += (char)(0x80 | (c & 0x3F)); }
    else if (c < 0x10000) { o += (char)(0xE0 | (c >> 12)); o += (char)(0x80 | ((c >> 6) & 0x3F)); o += (char)(0x80 | (c & 0x3F)); }
    else { o += (char)(0xF0 | (c >> 18)); o += (char)(0x80 | ((c >> 12) & 0x3F)); o += (char)(0x80 | ((c >> 6) & 0x3F)); o += (char)(0x80 | (c & 0x3F)); }
}

std::string ebuLatin(const uint8_t* p, size_t n) {
    std::string o;
    for (size_t i = 0; i < n; i++) appendUtf8(o, kEbuLatin[p[i]]);
    return o;
}

std::string ucs2be(const uint8_t* p, size_t n) {
    std::string o;
    for (size_t i = 0; i + 1 < n; i += 2) {
        uint32_t c = ((uint32_t)p[i] << 8) | p[i + 1];
        if (c >= 0xD800 && c <= 0xDBFF && i + 3 < n) {   // a surrogate pair (UTF-16 sent as "UCS-2")
            const uint32_t d = ((uint32_t)p[i + 2] << 8) | p[i + 3];
            if (d >= 0xDC00 && d <= 0xDFFF) { c = 0x10000 + ((c - 0xD800) << 10) + (d - 0xDC00); i += 2; }
        }
        appendUtf8(o, c);
    }
    return o;
}

std::string dabCharset(int cs, const uint8_t* p, size_t n) {
    switch (cs) {
    case 4: { std::string o; for (size_t i = 0; i < n; i++) appendUtf8(o, p[i]); return o; }
    case 6: return ucs2be(p, n);
    case 15: return std::string((const char*)p, n);   // clean() drops what is not valid UTF-8
    default: return ebuLatin(p, n);
    }
}

std::string iso6937(const uint8_t* p, size_t n) {
    std::string o;
    for (size_t i = 0; i < n; i++) {
        const uint8_t c = p[i];
        if (c < 0xA0) { appendUtf8(o, c); continue; }   // ASCII, and the C1 codes DVB uses for emphasis and line breaks (clean() handles them)
        if (c >= 0xC1 && c <= 0xCF) {
            if (i + 1 < n && p[i + 1] >= 0x20 && p[i + 1] < 0x80) {
                const uint16_t u = kIso6937Comb[c - 0xC1][p[i + 1] - 0x20];
                if (u) appendUtf8(o, u); else appendUtf8(o, p[i + 1]);   // an accent the letter does not take: keep the letter
                i++;
            }
            continue;
        }
        if (const uint16_t u = kIso6937Hi[c - 0xA0]) appendUtf8(o, u);
    }
    return o;
}

std::string clean(const std::string& s) {
    std::string o;
    bool space = false;
    auto put = [&](uint32_t c) {
        if (c == '\t' || c == '\n' || c == '\r' || c == 0x8A || c == 0x2028 || c == 0x2029 || c == 0xA0 || c == 0x3000) c = ' ';
        if (c == ' ') { space = !o.empty(); return; }
        if (invisible(c)) return;
        if (space) { o += ' '; space = false; }
        appendUtf8(o, c);
    };
    const size_t n = s.size();
    for (size_t i = 0; i < n;) {
        const uint8_t b = (uint8_t)s[i];
        int len = b < 0x80 ? 1 : (b >> 5) == 6 ? 2 : (b >> 4) == 14 ? 3 : (b >> 3) == 30 ? 4 : 0;
        if (!len || i + len > n) { i++; continue; }   // not valid UTF-8: drop the byte
        uint32_t c = len == 1 ? b : len == 2 ? (b & 0x1F) : len == 3 ? (b & 0x0F) : (b & 0x07);
        bool ok = true;
        for (int k = 1; k < len; k++) {
            const uint8_t t = (uint8_t)s[i + k];
            if ((t & 0xC0) != 0x80) { ok = false; break; }
            c = (c << 6) | (t & 0x3F);
        }
        static const uint32_t minFor[5] = {0, 0, 0x80, 0x800, 0x10000};
        if (!ok || c < minFor[len]) { i++; continue; }   // broken or over-long sequence
        put(c);
        i += (size_t)len;
    }
    return o;
}
