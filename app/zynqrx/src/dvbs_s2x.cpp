void s2xBuildConstellation(const S2xModcod& m, std::vector<cf32>& pts) {
    double R[8] = {1, 1, 1, 1, 1, 1, 1, 1};
    for (int i = 0; i < 7; i++) R[i + 1] = m.g[i];
    switch (m.shape) {
    case kSh242: {
        // table 10a: label p00 R1, p01 R2, p10 R2, p11 R3; the angle over pi for p = 0 and p = 1
        static const struct { const char* l; int ring; double a0, a1; } t[4] = {
            {"00", 1, 1, 0}, {"01", 2, 1 + 0.352, -0.352}, {"10", 2, 1 - 0.352, 0.352}, {"11", 3, 1, 0}};
        pts.assign(8, cf32());
        for (const auto& r : t)
            for (int p = 0; p < 2; p++) pts[(unsigned)(p << 2 | std::strtol(r.l, nullptr, 2))] = polar(R[r.ring - 1], p ? r.a1 : r.a0);
        break;
    }
    case kSh88: fromAngles(k88, 4, 4, R, pts); break;
    case kSh88Tab18: case kSh88Tab20: {
        const int col = m.shape == kSh88Tab18 ? 0 : 1;
        pts.assign(16, cf32());
        for (int l = 0; l < 16; l++) pts[(size_t)l] = cf32(k88Points[l][col][0], k88Points[l][col][1]);
        break;
    }
    case kSh41216rb: fromAngles(k41216rb, 8, 5, R, pts); break;
    case kSh48416: fromAngles(k48416, 8, 5, R, pts); break;
    case kSh16x4: fromAngles(k16x4, 16, 6, R, pts); break;
    case kSh8162020: fromAngles(k8162020, 16, 6, R, pts); break;
    case kSh4122028: fromAngles(k4122028, 16, 6, R, pts); break;
    case kSh128: fromAngles(k128, 32, 7, R, pts); break;
    case kSh256: {
        // label rrrqpaaa: columns p = q = 0: phi, p = 0 q = 1: -phi, p = 1 q = 0: pi - phi, p = q = 1: pi + phi
        pts.assign(256, cf32());
        for (int l = 0; l < 256; l++) {
            const int q = (l >> 4) & 1, p = (l >> 3) & 1;
            const double phi = (2.0 * k256Phi[l & 7] - 1.0) / 32.0;
            const double a = p == 0 && q == 0 ? phi : p == 0 ? -phi : q == 0 ? 1 - phi : 1 + phi;
            pts[(size_t)l] = polar(R[k256Ring[l >> 5] - 1], a);
        }
        break;
    }
    case kSh256Tab20: case kSh256Tab22: {
        const int col = m.shape == kSh256Tab20 ? 0 : 1;
        pts.assign(256, cf32());
        for (int l = 0; l < 256; l++) pts[(size_t)l] = cf32(k256Points[l][col][0], k256Points[l][col][1]);
        break;
    }
    default: pts.clear(); return;    // kShS2 and kSh412 are built with the DVB-S2 ones
    }
    normalise(pts);
}

