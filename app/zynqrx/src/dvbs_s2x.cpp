double fraction(const char* s) {
    char* e = nullptr;
    const double a = std::strtod(s, &e);
    return *e == '/' ? a / std::strtod(e + 1, nullptr) : a;
}
cf32 polar(double r, double turnsOfPi) { return cf32((float)(r * std::cos(turnsOfPi * kPi)), (float)(r * std::sin(turnsOfPi * kPi))); }

void fromAngles(const AngleRow* rows, int n, int bits, const double* radius, std::vector<cf32>& pts) {
    pts.assign((size_t)1 << bits, cf32());
    for (int r = 0; r < n; r++)
        for (int c = 0; c < 4; c++) {
            const int p = c >> 1, q = c & 1;
            unsigned label = 0;
            for (const char* s = rows[r].label; *s; s++) label = label << 1 | (unsigned)(*s == 'p' ? p : *s == 'q' ? q : *s - '0');
            pts[label] = polar(radius[rows[r].ring - 1], fraction(rows[r].a[c]));
        }
}

void normalise(std::vector<cf32>& pts) {
    double e = 0;
    for (const cf32& p : pts) e += std::norm(p);
    const float s = (float)(1.0 / std::sqrt(e / (double)pts.size()));
    for (cf32& p : pts) p *= s;
}
